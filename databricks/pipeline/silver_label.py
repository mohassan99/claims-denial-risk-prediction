"""
Silver label: the Spark counterpart of denial_reasons.sample_denials() +
apply_payment_consequence() + build_target_and_split.write_label_audit().

The six risk-factor rules are re-expressed as Spark groupbys / windows (this is
the part that needs the whole dataset in memory in pandas). Every rule
parameter comes from src/denial_rules.py and src/denial_reasons.py.

WHAT RUNS ON THE DRIVER, AND WHY. The label is a Bernoulli draw, and its
random numbers come from numpy's PCG64 generator seeded 42, consumed in
_row_id order: first one uniform per claim line (is_denied), then one more per
denied multi-factor line (the 30% second-reason draw). Spark has no way to
reproduce that exact stream, and re-drawing with a Spark RNG would silently
change is_denied for thousands of claims -- a label change, which this project
doesn't make without a decision. So the draws are generated by the same numpy
calls, keyed by _row_id, and joined back. They're small (one float per row),
so this costs seconds, not memory. The same applies to the payment-noise draw
(seed 43), which only touches CLM_PMT_AMT, a leakage column dropped before any
modeling table.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from pyspark.sql import DataFrame, Window
from pyspark.sql import functions as F

from .common import table, write_delta

import denial_rules as dr  # noqa: E402
import denial_reasons as dreas  # noqa: E402
from build_target_and_split import CALIBRATION_SCALE, ZERO_CELL_MIN_CLAIMS  # noqa: E402

RISK_ORDER = list(dreas.RISK_FACTOR_FUNCS)  # column order of compute_risk_factors()
DATE_FMT = "dd-MMM-yyyy"  # CMS RIF dates look like 28-Sep-2015


def _provider_key_and_pool(df: DataFrame) -> DataFrame:
    key = pool = None
    for source, (col, prefix) in dr.PROVIDER_KEY_SOURCE.items():
        cond, val = F.col("_source_file") == source, F.concat(F.lit(prefix), F.col(col))  # null col -> null key
        key = F.when(cond, val) if key is None else key.when(cond, val)
    for source, p in dr.PROVIDER_POOL.items():
        cond = F.col("_source_file") == source
        pool = F.when(cond, F.lit(p)) if pool is None else pool.when(cond, F.lit(p))
    return df.withColumn("_provider_key", key).withColumn("_provider_pool", pool)


def _require_key_coverage(df: DataFrame, rule: str, keys: list[str], allowed: set[tuple[str, str]] = frozenset()) -> None:
    """Same guardrail as denial_rules.require_key_coverage: a group key that is
    >1% null in some claim type would silently disable the rule there."""
    unknown = [r["_source_file"] for r in df.select("_source_file").distinct().collect()
               if r["_source_file"] not in dr.PROVIDER_KEY_SOURCE]
    if unknown:
        raise ValueError(f"No provider-key field declared for claim file(s) {sorted(unknown)}")
    shares = df.groupBy("_source_file").agg(
        *[F.avg(F.col(k).isNull().cast("double")).alias(k) for k in keys]
    ).collect()
    problems = [f"{k} is {r[k]:.1%} null in {r['_source_file']}"
                for r in shares for k in keys
                if r[k] > 0.01 and (k, r["_source_file"]) not in allowed]
    if problems:
        raise ValueError(f"{rule}: group key(s) not populated: " + "; ".join(problems))


def compute_risk_factors(claims: DataFrame) -> DataFrame:
    """One boolean column per risk factor, keyed by _row_id."""
    df = _provider_key_and_pool(claims.select(
        "_row_id", "_source_file", "BENE_ID", "CLM_ID", "HCPCS_CD", "CLM_FROM_DT",
        "PRNCPAL_DGNS_CD", "LINE_NUM", "CLM_PMT_AMT", "CARR_CLM_BLG_NPI_NUM", "PRVDR_NUM",
    )).withColumn("_date", F.to_date("CLM_FROM_DT", DATE_FMT))

    _require_key_coverage(df, "provider_outlier", ["_provider_key"])
    _require_key_coverage(df, "duplicate_claim", ["BENE_ID", "HCPCS_CD", "CLM_FROM_DT", "_provider_key"],
                          allowed={("HCPCS_CD", "carrier.csv")})

    hcpcs = F.col("HCPCS_CD")

    # missing_hcpcs: no code, except carrier LINE_NUM == "1" (rule_missing_hcpcs)
    missing_hcpcs = hcpcs.isNull() & ~F.coalesce(
        (F.col("_source_file") == "carrier.csv") & (F.col("LINE_NUM") == "1"), F.lit(False))

    # deprecated_code: non-payable consult code on/after 2010-01-01
    eff = dr.MEDICARE_CONSULT_NONPAY_EFFECTIVE_DATE.date().isoformat()
    deprecated = F.coalesce(hcpcs.isin(sorted(dr.MEDICARE_NONPAYABLE_CONSULT_CODES))
                            & (F.col("_date") >= F.lit(eff).cast("date")), F.lit(False))

    # dx_procedure_mismatch: mapped code whose principal dx isn't in the
    # expected ICD-10 chapter(s). A null dx never matches (pandas: "nan"[0]).
    dx_first = F.substring(F.col("PRNCPAL_DGNS_CD"), 1, 1)
    mismatch = F.lit(False)
    for code, prefixes in dr.PROCEDURE_TO_EXPECTED_DX_PREFIX.items():
        mismatch = mismatch | ((hcpcs == code) & ~F.coalesce(dx_first.isin(list(prefixes)), F.lit(False)))
    mismatch = F.coalesce(mismatch, F.lit(False))

    # missing_prior_auth: E*/K* code with no claim for the same beneficiary in
    # the prior LOOKBACK_DAYS. pandas sorts by (bene, date) with a stable sort
    # (ties keep original order, NaT last) and diffs consecutive rows.
    w = Window.partitionBy("BENE_ID").orderBy(F.col("_date").asc_nulls_last(), F.col("_row_id"))
    gap = F.datediff(F.col("_date"), F.lag("_date").over(w))
    high_cost = F.coalesce(
        reduce_or([hcpcs.startswith(p) for p in dr.HIGH_COST_HCPCS_PREFIXES]), F.lit(False))
    prior_auth = high_cost & (gap.isNull() | (gap > dr.LOOKBACK_DAYS))

    # duplicate_claim: same (bene, code, raw date string, provider key) on >1
    # distinct CLM_ID. Any null key -> not flagged (pandas groupby drops it).
    dup_keys = ["BENE_ID", "HCPCS_CD", "CLM_FROM_DT", "_provider_key"]
    dups = (df.where(reduce_and([F.col(k).isNotNull() for k in dup_keys]))
            .groupBy(*dup_keys).agg(F.countDistinct("CLM_ID").alias("_n_clm"))
            .where(F.col("_n_clm") > 1).select(*dup_keys, F.lit(True).alias("_dup")))

    # provider_outlier: top-5% providers by claim count OR total native
    # payment, within pool. pandas .quantile() = linear interpolation, which is
    # what Spark's exact percentile() computes too. sum over all-null -> 0.
    stats = (df.where(F.col("_provider_key").isNotNull())
             .groupBy("_provider_pool", "_provider_key")
             .agg(F.count(F.lit(1)).alias("claim_count"),
                  F.coalesce(F.sum("CLM_PMT_AMT"), F.lit(0.0)).alias("total_paid")))
    cuts = stats.groupBy("_provider_pool").agg(
        F.percentile("claim_count", 0.95).alias("vol_cut"),
        F.percentile("total_paid", 0.95).alias("pay_cut"))
    outliers = (stats.join(cuts, "_provider_pool")
                .where((F.col("claim_count") >= F.col("vol_cut")) | (F.col("total_paid") >= F.col("pay_cut")))
                .select("_provider_key").distinct().withColumn("_outlier", F.lit(True)))

    flagged = (df.withColumn("missing_hcpcs", missing_hcpcs)
               .withColumn("deprecated_code", deprecated)
               .withColumn("missing_prior_auth", prior_auth)
               .withColumn("dx_procedure_mismatch", mismatch)
               .join(dups, dup_keys, "left")
               .join(outliers, "_provider_key", "left")
               .withColumn("duplicate_claim", F.coalesce(F.col("_dup"), F.lit(False)))
               .withColumn("provider_outlier", F.coalesce(F.col("_outlier"), F.lit(False))))
    return flagged.select("_row_id", "_source_file", "HCPCS_CD", *RISK_ORDER)


def reduce_or(exprs):
    out = exprs[0]
    for e in exprs[1:]:
        out = out | e
    return out


def reduce_and(exprs):
    out = exprs[0]
    for e in exprs[1:]:
        out = out & e
    return out


def base_probabilities() -> dict[str, float]:
    probs = {k: (v["base_prob"] if k in dreas.UNCALIBRATED_FACTORS else v["base_prob"] * CALIBRATION_SCALE)
             for k, v in dreas.REASON_CATALOG.items()}
    return {k: min(p, 0.95) for k, p in probs.items()}


def noisy_or(risk: DataFrame) -> DataFrame:
    """P(denied) = 1 - prod(1 - p_i) over active factors, multiplied in the
    same order as denial_reasons.noisy_or_probability so the doubles match
    bit for bit."""
    probs = base_probabilities()
    survival = F.lit(1.0)
    for f in RISK_ORDER:
        survival = survival * F.when(F.col(f), F.lit(1 - probs[f])).otherwise(F.lit(1.0))
    return risk.withColumn("p_denied_model", F.lit(1.0) - survival)


def draw_labels(spark, risk: DataFrame, n_rows: int) -> DataFrame:
    """is_denied + reason codes, from the same numpy draws as sample_denials()."""
    rng = np.random.default_rng(42)
    u = rng.random(n_rows)  # one per claim line, in _row_id order

    p = risk.select("_row_id", "p_denied_model").toPandas().sort_values("_row_id")
    if not (p["_row_id"].to_numpy() == np.arange(n_rows)).all():
        raise ValueError("_row_id is not a dense 0..n-1 range -- draws can't be keyed to it")
    is_denied = (u < p["p_denied_model"].to_numpy()).astype(int)

    # Reasons: fixed priority for the first; the 30% second-reason draw
    # continues the SAME generator, over denied rows in _row_id order.
    denied_ids = np.flatnonzero(is_denied)
    flags = (risk.select("_row_id", *RISK_ORDER)
             .join(spark.createDataFrame(pd.DataFrame({"_row_id": denied_ids.astype("int64")})), "_row_id")
             .toPandas().sort_values("_row_id").reset_index(drop=True))
    carc = {f: dreas.REASON_CATALOG[f]["carc_code"] for f in RISK_ORDER}
    prio = [f for f in dreas.REASON_PRIORITY if f in RISK_ORDER]
    r1, r2 = [], []
    for row in flags[prio].itertuples(index=False):
        active = [f for f, on in zip(prio, row) if on]
        if not active:
            r1.append(None); r2.append(None); continue
        r1.append(carc[active[0]])
        r2.append(carc[active[1]] if len(active) > 1 and rng.random() < 0.30 else None)

    # Payment consequence (apply_payment_consequence): separate generator.
    noise = np.random.default_rng(43).uniform(0, 2.00, size=len(denied_ids))

    labels = pd.DataFrame({"_row_id": np.arange(n_rows, dtype="int64"), "is_denied": is_denied.astype("int64")})
    reasons = pd.DataFrame({
        "_row_id": flags["_row_id"].astype("int64"),
        "denial_reason_carc_1": pd.array(r1, dtype="object"),
        "denial_reason_carc_2": pd.array(r2, dtype="object"),
        "_pmt_noise": noise,
    })
    return (spark.createDataFrame(labels)
            .join(spark.createDataFrame(reasons, schema="_row_id long, denial_reason_carc_1 string, denial_reason_carc_2 string, _pmt_noise double"),
                  "_row_id", "left"))


def audit_by_claim_type(risk: DataFrame) -> pd.DataFrame:
    """RISK_FACTOR_EXPECTATION check, same rules as
    denial_reasons.audit_risk_factors_by_claim_type (raises on violation)."""
    rates = (risk.groupBy("_source_file").agg(*[F.avg(F.col(f).cast("double")).alias(f) for f in RISK_ORDER])
             .toPandas().set_index("_source_file").sort_index().T)
    problems = []
    for factor in rates.index:
        expected = dreas.RISK_FACTOR_EXPECTATION.get(factor, {})
        for source in rates.columns:
            rate, rule = rates.loc[factor, source], expected.get(source)
            if rule is None:
                problems.append(f"{factor} x {source}: no expectation declared")
            elif rule == "fires" and rate == 0:
                problems.append(f"{factor} x {source}: expected to fire, fires on 0 claims")
            elif rule.startswith("zero") and rate > 0:
                problems.append(f"{factor} x {source}: declared '{rule}', but fires on {rate:.4%}")
    if problems:
        raise ValueError("Risk-factor-by-claim-type audit failed:\n  " + "\n  ".join(problems))
    return rates


def label_audit_text(labeled: DataFrame, rates: pd.DataFrame) -> str:
    """reports/label_audit.txt, formatted by the same pandas calls as
    build_target_and_split.write_label_audit so the two files can be diffed."""
    by_type = (labeled.groupBy("_source_file").agg(F.count(F.lit(1)).alias("size"), F.avg("is_denied").alias("mean"))
               .toPandas().set_index("_source_file").sort_index())
    by_type.index.name = None
    cells = (labeled.withColumn("code", F.coalesce(F.col("HCPCS_CD"), F.lit("<missing>")))
             .groupBy("_source_file", "code").agg(F.count(F.lit(1)).alias("size"), F.sum("is_denied").alias("sum"))
             .toPandas().set_index(["_source_file", "code"]).sort_index())
    cells.index.names = [None, None]
    zero = cells[(cells["sum"] == 0) & (cells["size"] >= ZERO_CELL_MIN_CLAIMS)].sort_values("size", ascending=False)
    overall = labeled.agg(F.avg("is_denied")).collect()[0][0]
    rates = rates.copy()
    rates.columns.name = None
    lines = [
        "Label audit -- written by build_target_and_split.py on every build",
        "=" * 66,
        f"Overall is_denied rate: {overall:.2%}",
        "",
        "Denial rate by claim type:",
        by_type.to_string(),
        "",
        "Risk-factor firing rate by claim type (every cell checked against",
        "denial_reasons.RISK_FACTOR_EXPECTATION -- this build passed):",
        rates.round(4).to_string(),
        "",
        f"Claim-type x HCPCS cells with >= {ZERO_CELL_MIN_CLAIMS:,} claims and ZERO denials: {len(zero)}",
        (zero.to_string() if len(zero) else "(none)"),
    ]
    return "\n".join(lines) + "\n"


def build_silver_labeled(spark, claims: DataFrame) -> tuple[DataFrame, str]:
    n_rows = claims.count()
    risk = noisy_or(compute_risk_factors(claims))
    write_delta(risk, "silver_risk_factors",
                "Per-claim-line risk-factor flags + noisy-OR P(denied), keyed by _row_id")
    risk = spark.table(table("silver_risk_factors"))
    rates = audit_by_claim_type(risk)
    labels = draw_labels(spark, risk, n_rows)

    risk_cols = [F.col(f).alias(f"risk_{f}") for f in RISK_ORDER]
    labeled = (claims.join(risk.select("_row_id", *risk_cols, "p_denied_model"), "_row_id")
               .join(labels, "_row_id")
               # apply_payment_consequence: denied lines get the small residual
               .withColumn("CLM_PMT_AMT", F.when(F.col("is_denied") == 1, F.col("_pmt_noise")).otherwise(F.col("CLM_PMT_AMT")))
               .drop("_pmt_noise"))
    ordered = [c for c in claims.columns] + [f"risk_{f}" for f in RISK_ORDER] + [
        "p_denied_model", "is_denied", "denial_reason_carc_1", "denial_reason_carc_2"]
    write_delta(labeled.select(*ordered), "silver_claims_labeled",
                "silver_claims + risk factors, P(denied), is_denied, CARC reasons (CLM_PMT_AMT is post-label: leakage)")
    labeled = spark.table(table("silver_claims_labeled"))
    return labeled, label_audit_text(labeled, rates)
